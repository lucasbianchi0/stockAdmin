/*
 * Ejercicios contables con fechas propias — ADITIVO, en prueba.
 *
 * Hasta acá el ejercicio de un asiento es el año calendario de su fecha. El de
 * Accedra cierra el 31 de agosto, así que desde el 1/9/2026 los asientos siguen
 * numerados como parte del ejercicio que terminó.
 *
 * Esta migración NO toca nada de lo que existe: ni `asientos`, ni sus números,
 * ni las funciones que los generan. Agrega:
 *
 *  · `ejercicios`: cada ejercicio con su inicio, su fin y su estado.
 *  · `asientos_por_ejercicio`: una vista que le asigna a cada asiento su
 *    ejercicio según la fecha y un número correlativo dentro de él, por fecha.
 *
 * Es para que la persona lo valide en el link de prueba. Si se aprueba, el paso
 * siguiente es fijar ese número en la tabla; si no, `supabase/revertir/20261016_01_ejercicios.sql`
 * borra lo de acá y la base queda como estaba.
 */

create table if not exists ejercicios (
  id smallint generated by default as identity primary key,
  inicio date not null,
  fin date not null,
  estado text not null default 'abierto' check (estado in ('abierto', 'cerrado')),
  created_at timestamptz not null default now(),
  check (fin >= inicio)
);

create unique index if not exists ejercicios_inicio_unico on ejercicios (inicio);

alter table ejercicios enable row level security;

/** "2026/27", o "2026" si empieza y termina el mismo año. */
create or replace function ejercicio_nombre(p_inicio date, p_fin date)
returns text language sql immutable as $$
  select case
    when extract(year from p_inicio) = extract(year from p_fin)
      then extract(year from p_fin)::text
    else extract(year from p_inicio)::text || '/' ||
         lpad((extract(year from p_fin)::int % 100)::text, 2, '0')
  end
$$;

