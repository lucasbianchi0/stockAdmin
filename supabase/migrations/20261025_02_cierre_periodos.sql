/*
 * Cierre de períodos — el pedido del estudio de octubre de 2026.
 *
 *   «Tenemos que poder tener la opción de en determinada fecha bloquear un
 *    período para que una vez cerrado el mes ya no se pueda cargar nada en ese
 *    periodo (…) que me permita bloquearlos para que nadie pueda ingresar nada
 *    para atrás.»
 *
 * ── Una sola fecha, no una lista de meses ───────────────────────────────────
 *
 * Lo que se guarda es «cerrado hasta el día X»: todo lo que tenga fecha
 * contable menor o igual queda bloqueado. Meses sueltos cerrados con un hueco
 * abierto en el medio no tienen sentido contable —el saldo del mes abierto
 * arrastra a todos los que siguen— y obligarían a explicar qué pasa con ellos.
 *
 * `cierres_periodo` es el historial completo (quién, cuándo, hasta dónde y por
 * qué) y la fecha vigente es la de la última fila. Reabrir no borra nada: es
 * una fila más, con una fecha anterior (o sin fecha, si se reabre todo). Por eso
 * la tabla no admite UPDATE ni DELETE.
 *
 * ── Por qué el candado está en la base ──────────────────────────────────────
 *
 * Por lo mismo que el motor de asientos: hay demasiados caminos que escriben
 * (alta manual, carga inteligente, importadores, recibos, extracto, imputar
 * pendientes) y la app usa la service role para todo. Un chequeo en TypeScript
 * se saltea el día que alguien agregue un camino nuevo. Acá no hay excepción
 * para la service role: es justamente la que usa la app.
 *
 * ── Qué fecha manda en cada tabla ───────────────────────────────────────────
 *
 *  · comprobantes, comprobante_ivas, comprobante_registro: la fecha de
 *    REGISTRO (20261016_02), que es la que define el período de una factura.
 *    Solo los confirmados: un borrador todavía no es un hecho contable —el
 *    mismo criterio con el que el motor no lo asienta—, y es lo que permite
 *    cargar una factura vieja que llegó tarde: se guarda como borrador, se le
 *    pone la fecha de registro del mes abierto y recién ahí se confirma.
 *  · pagos y sus hijos (imputaciones, pago_retenciones, pago_aplicaciones): la
 *    fecha del recibo.
 *  · movimientos: la suya y, si cuelga de un recibo, también la del recibo.
 *  · asientos y asiento_lineas: la del asiento; para el de una factura, su
 *    fecha de registro. Es la red de abajo: con los documentos ya frenados,
 *    acá solo debería llegar un asiento manual.
 *
 * En un UPDATE o DELETE se miran la fila vieja y la nueva: mover algo de un mes
 * cerrado a uno abierto también es modificar el mes cerrado.
 *
 * Lo que NO se bloquea: asientos_borradores (se arman y se revisan; registrar
 * uno sí queda frenado si su fecha está cerrada), stock (no toca contabilidad)
 * y la fecha estimada de pago de una factura, que es planificación de caja y no
 * contabilidad — ver `comprobante_solo_gestion`.
 *
 * Revertir: supabase/revertir/20261025_02_cierre_periodos.sql
 */

/* ── 1 · El historial ─────────────────────────────────────────────────────── */

create table if not exists cierres_periodo (
  id bigint generated by default as identity primary key,
  -- Cerrado hasta este día inclusive. Null = no hay nada cerrado (una
  -- reapertura total).
  hasta date,
  accion text not null check (accion in ('cierre', 'reapertura')),
  motivo text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id) on delete set null
);

alter table cierres_periodo enable row level security;

-- Es un registro de auditoría: lo que se escribió queda. Corregir un cierre es
-- cargar otra fila, no editar la anterior.
create or replace function tg_cierres_periodo_inmutable() returns trigger
language plpgsql as $$
begin
  raise exception 'El historial de cierres no se modifica: cargá un cierre o una reapertura nueva.';
end $$;

drop trigger if exists cierres_periodo_inmutable on cierres_periodo;
create trigger cierres_periodo_inmutable
  before update or delete on cierres_periodo
  for each row execute function tg_cierres_periodo_inmutable();

/* ── 2 · Ayudantes ────────────────────────────────────────────────────────── */

/*
 * La fecha vigente. `security definer` para que la lea cualquier rol que llegue
 * a escribir: con RLS activo y sin políticas, un rol que no sea la service role
 * vería la tabla vacía y el candado quedaría abierto sin que nadie lo note.
 */
create or replace function fecha_cierre_contable() returns date
language sql stable security definer set search_path = public as $$
  select hasta from cierres_periodo order by id desc limit 1;
$$;

/*
 * El chequeo en sí. Código propio (PC001) para que la app lo reconozca y le
 * muestre el mensaje tal cual a la persona, en vez del «No se pudo guardar» de
 * siempre.
 */
create or replace function cierre_verificar(p_fecha date) returns void
language plpgsql stable as $$
declare
  v_hasta date := fecha_cierre_contable();
begin
  if p_fecha is null or v_hasta is null or p_fecha > v_hasta then
    return;
  end if;
  raise exception
    'El período está cerrado hasta el %: no se puede cargar ni modificar nada con fecha anterior.',
    to_char(v_hasta, 'DD/MM/YYYY')
    using errcode = 'PC001',
          detail  = 'Fecha del movimiento: ' || to_char(p_fecha, 'DD/MM/YYYY') || '.',
          hint    = 'Si hay que corregir algo de ese período, un administrador lo puede reabrir desde Contabilidad → Cierre de períodos.';
end $$;

/* La fecha de registro de una factura: la de `comprobante_registro` si tiene,
 * y si no la del comprobante (igual que la vista `comprobantes_fecha_registro`,
 * pero con la fecha que se le pase, que en un trigger puede ser la de OLD). */
create or replace function comprobante_fecha_periodo(p_id uuid, p_fecha date) returns date
language sql stable as $$
  select coalesce(
    (select fecha_registro from comprobante_registro where comprobante_id = p_id),
    p_fecha
  );
$$;

/* La fecha de un recibo, para sus hijos. Null si ya no existe: pasa en el
 * cascade de un recibo que se borra, y ahí el que se chequeó fue el recibo. */
create or replace function pago_fecha_periodo(p_id uuid) returns date
language sql stable as $$
  select fecha from pagos where id = p_id;
$$;

/*
 * ¿Lo único que cambió es la fecha estimada de pago?
 *
 * Es planificación de caja: decidir cuándo se paga una factura vieja que sigue
 * impaga es justamente lo que se hace con los meses ya cerrados. Hasta hoy
 * cambiarla rehacía el asiento entero —y le daba un número nuevo— sin que
 * cambiara nada de él; con el cierre, encima, lo haría fallar.
 *
 * Se comparan las filas enteras menos esa columna, `updated_at` y las
 * generadas, que en un trigger BEFORE todavía vienen en null. Si mañana se
 * agrega otra columna generada y no se suma acá, esto da false: el error es
 * frenar de más, nunca dejar pasar.
 */
create or replace function comprobante_solo_gestion(o comprobantes, n comprobantes) returns boolean
language sql stable as $$
  select o.fecha_estimada_pago is distinct from n.fecha_estimada_pago
     and (to_jsonb(o) - array['fecha_estimada_pago', 'updated_at', 'signo', 'total_ars', 'total_usd'])
       = (to_jsonb(n) - array['fecha_estimada_pago', 'updated_at', 'signo', 'total_ars', 'total_usd']);
$$;

/* ── 3 · Los candados ─────────────────────────────────────────────────────── */

/*
 * Todos los triggers se llaman `a_cierre_periodo`: Postgres corre los BEFORE de
 * una tabla por orden alfabético, y así el del cierre va primero y la persona
 * ve su mensaje y no el de otro trigger que tropezó con lo mismo.
 */

create or replace function tg_cierre_comprobante() returns trigger
language plpgsql as $$
begin
  if tg_op = 'UPDATE' and old.estado = 'confirmado' and new.estado = 'confirmado'
     and comprobante_solo_gestion(old, new) then
    return new;
  end if;

  if tg_op in ('UPDATE', 'DELETE') and old.estado = 'confirmado' then
    perform cierre_verificar(comprobante_fecha_periodo(old.id, old.fecha));
  end if;
  if tg_op in ('INSERT', 'UPDATE') and new.estado = 'confirmado' then
    perform cierre_verificar(comprobante_fecha_periodo(new.id, new.fecha));
  end if;

  if tg_op = 'DELETE' then
    -- El asiento se borra acá y no esperando al trigger AFTER del motor: para
    -- entonces el cascade ya se llevó la fecha de registro, y el candado de
    -- `asientos` vería la del comprobante, que puede estar cerrada aunque la
    -- factura sea de un mes abierto.
    perform asiento_borrar('comprobante', old.id);
    return old;
  end if;
  return new;
end $$;

drop trigger if exists a_cierre_periodo on comprobantes;
create trigger a_cierre_periodo
  before insert or update or delete on comprobantes
  for each row execute function tg_cierre_comprobante();

/* El desglose por alícuota es parte de la factura. Sin comprobante (o si no
 * está confirmado) no hay nada que chequear: es el cascade de uno que se borra
 * —que ya se chequeó— o un borrador. */
create or replace function cierre_verificar_comprobante(p_id uuid) returns void
language plpgsql stable as $$
declare
  v_fecha date;
begin
  select fecha into v_fecha from comprobantes where id = p_id and estado = 'confirmado';
  if found then
    perform cierre_verificar(comprobante_fecha_periodo(p_id, v_fecha));
  end if;
end $$;

create or replace function tg_cierre_comprobante_hijo() returns trigger
language plpgsql as $$
begin
  if tg_op <> 'INSERT' then perform cierre_verificar_comprobante(old.comprobante_id); end if;
  if tg_op <> 'DELETE' then perform cierre_verificar_comprobante(new.comprobante_id); end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists a_cierre_periodo on comprobante_ivas;
create trigger a_cierre_periodo
  before insert or update or delete on comprobante_ivas
  for each row execute function tg_cierre_comprobante_hijo();

/*
 * Cambiar la fecha de registro mueve la factura de período: se chequean la de
 * antes y la de después. Sin fila, la fecha es la del comprobante, así que
 * crearla parte de esa y borrarla vuelve a esa.
 */
create or replace function tg_cierre_comprobante_registro() returns trigger
language plpgsql as $$
declare
  v_id    uuid;
  v_fecha date;
begin
  if tg_op = 'DELETE' then v_id := old.comprobante_id; else v_id := new.comprobante_id; end if;
  select fecha into v_fecha from comprobantes where id = v_id and estado = 'confirmado';

  -- Sin comprobante es el cascade de uno que se borra, que ya se chequeó; un
  -- borrador no tiene período todavía.
  if not found then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_op = 'INSERT' then
    perform cierre_verificar(v_fecha);
  else
    perform cierre_verificar(old.fecha_registro);
  end if;

  if tg_op = 'DELETE' then
    perform cierre_verificar(v_fecha);
    return old;
  end if;
  perform cierre_verificar(new.fecha_registro);
  return new;
end $$;

drop trigger if exists a_cierre_periodo on comprobante_registro;
create trigger a_cierre_periodo
  before insert or update or delete on comprobante_registro
  for each row execute function tg_cierre_comprobante_registro();

create or replace function tg_cierre_pago() returns trigger
language plpgsql as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then perform cierre_verificar(old.fecha); end if;
  if tg_op in ('INSERT', 'UPDATE') then perform cierre_verificar(new.fecha); end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists a_cierre_periodo on pagos;
create trigger a_cierre_periodo
  before insert or update or delete on pagos
  for each row execute function tg_cierre_pago();

/*
 * Lo que cuelga de un recibo arma su asiento: imputaciones y retenciones por
 * `pago_id`, las aplicaciones de anticipos por `pago_destino_id` (el recibo
 * que consume; el anticipo de origen no cambia por aplicarlo). Una función por
 * columna porque `new.pago_id` no existe en la tabla que no la tiene.
 */
create or replace function tg_cierre_hijo_de_pago() returns trigger
language plpgsql as $$
begin
  if tg_op <> 'INSERT' then perform cierre_verificar(pago_fecha_periodo(old.pago_id)); end if;
  if tg_op <> 'DELETE' then perform cierre_verificar(pago_fecha_periodo(new.pago_id)); end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

