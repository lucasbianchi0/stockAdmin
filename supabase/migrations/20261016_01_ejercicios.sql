/**
 * Cada asiento con su ejercicio y su número dentro de él.
 *
 * El número se calcula, no se guarda: por fecha y, a igual fecha, en el orden en
 * que se registró. Mientras esto esté en prueba es lo que permite que mover el
 * inicio de un ejercicio reacomode todo sin escribir un solo asiento.
 */
create or replace view asientos_por_ejercicio as
select a.id as asiento_id,
       e.id as ejercicio_id,
       ejercicio_nombre(e.inicio, e.fin) as ejercicio,
       row_number() over (
         partition by e.id order by a.fecha, a.numero, a.created_at, a.id
       ) as numero
  from asientos a
  join ejercicios e on a.fecha between e.inicio and e.fin;

create or replace view ejercicios_resumen as
select e.id, e.inicio, e.fin, e.estado,
       ejercicio_nombre(e.inicio, e.fin) as nombre,
       (select count(*) from asientos a where a.fecha between e.inicio and e.fin) as asientos,
       current_date between e.inicio and e.fin as en_curso
  from ejercicios e;

/*
 * Mover el límite entre dos ejercicios. Es la forma de "cambiar cuándo arranca
 * el ejercicio del año": el anterior termina el día antes (o el siguiente
 * empieza el día después). Un ejercicio cerrado no se mueve, ni el suyo ni el
 * vecino.
 */
create or replace function ejercicio_cambiar_inicio(p_id smallint, p_inicio date)
returns void language plpgsql as $$
declare
  e ejercicios%rowtype;
  v_anterior ejercicios%rowtype;
begin
  select * into e from ejercicios where id = p_id for update;
  if not found then raise exception 'Ese ejercicio no existe'; end if;
  if e.estado = 'cerrado' then raise exception 'El ejercicio está cerrado'; end if;
  if p_inicio > e.fin then raise exception 'El inicio no puede ser posterior al cierre'; end if;

  select * into v_anterior from ejercicios where fin = e.inicio - 1 for update;
  if found then
    if v_anterior.estado = 'cerrado' then
      raise exception 'El ejercicio anterior está cerrado: no se puede mover su cierre';
    end if;
    if p_inicio <= v_anterior.inicio then
      raise exception 'El ejercicio anterior quedaría sin días';
    end if;
    update ejercicios set fin = p_inicio - 1 where id = v_anterior.id;
  end if;

  update ejercicios set inicio = p_inicio where id = p_id;
end $$;

create or replace function ejercicio_cambiar_fin(p_id smallint, p_fin date)
returns void language plpgsql as $$
declare
  e ejercicios%rowtype;
  v_siguiente ejercicios%rowtype;
begin
  select * into e from ejercicios where id = p_id for update;
  if not found then raise exception 'Ese ejercicio no existe'; end if;
  if e.estado = 'cerrado' then raise exception 'El ejercicio está cerrado'; end if;
  if p_fin < e.inicio then raise exception 'El cierre no puede ser anterior al inicio'; end if;

  select * into v_siguiente from ejercicios where inicio = e.fin + 1 for update;
  if found then
    if v_siguiente.estado = 'cerrado' then raise exception 'El ejercicio siguiente está cerrado'; end if;
    if p_fin >= v_siguiente.fin then raise exception 'El ejercicio siguiente quedaría sin días'; end if;
    update ejercicios set inicio = p_fin + 1 where id = v_siguiente.id;
  end if;

  update ejercicios set fin = p_fin where id = p_id;
end $$;
