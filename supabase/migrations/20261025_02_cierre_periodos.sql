/* El movimiento de un recibo vive en el asiento del recibo, que va con la
 * fecha del recibo: se chequean las dos. */
create or replace function tg_cierre_movimiento() returns trigger
language plpgsql as $$
begin
  if tg_op <> 'INSERT' then
    perform cierre_verificar(old.fecha);
    if old.pago_id is not null then perform cierre_verificar(pago_fecha_periodo(old.pago_id)); end if;
  end if;
  if tg_op <> 'DELETE' then
    perform cierre_verificar(new.fecha);
    if new.pago_id is not null then perform cierre_verificar(pago_fecha_periodo(new.pago_id)); end if;
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists a_cierre_periodo on movimientos;
create trigger a_cierre_periodo
  before insert or update or delete on movimientos
  for each row execute function tg_cierre_movimiento();

/*
 * El libro diario. El asiento de una factura va con la fecha del comprobante
 * pero su período es el de registro: sin esto, editar una factura del 28/09
 * registrada en octubre —permitido— no podría rehacer su asiento.
 */
create or replace function asiento_fecha_periodo(p_origen text, p_origen_id uuid, p_fecha date)
returns date language sql stable as $$
  select case when p_origen = 'comprobante' and p_origen_id is not null
    then comprobante_fecha_periodo(p_origen_id, p_fecha)
    else p_fecha end;
$$;

create or replace function tg_cierre_asiento() returns trigger
language plpgsql as $$
begin
  if tg_op <> 'INSERT' then
    perform cierre_verificar(asiento_fecha_periodo(old.origen, old.origen_id, old.fecha));
  end if;
  if tg_op <> 'DELETE' then
    perform cierre_verificar(asiento_fecha_periodo(new.origen, new.origen_id, new.fecha));
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists a_cierre_periodo on asientos;
create trigger a_cierre_periodo
  before insert or update or delete on asientos
  for each row execute function tg_cierre_asiento();

/* Las líneas, por su cabecera. Sin cabecera es el cascade de un asiento que se
 * borra, que ya se chequeó. */
create or replace function cierre_verificar_asiento(p_id uuid) returns void
language plpgsql stable as $$
declare
  a record;
begin
  select origen, origen_id, fecha into a from asientos where id = p_id;
  if found then
    perform cierre_verificar(asiento_fecha_periodo(a.origen, a.origen_id, a.fecha));
  end if;
end $$;

create or replace function tg_cierre_asiento_linea() returns trigger
language plpgsql as $$
begin
  if tg_op <> 'INSERT' then perform cierre_verificar_asiento(old.asiento_id); end if;
  if tg_op <> 'DELETE' then perform cierre_verificar_asiento(new.asiento_id); end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists a_cierre_periodo on asiento_lineas;
create trigger a_cierre_periodo
  before insert or update or delete on asiento_lineas
  for each row execute function tg_cierre_asiento_linea();

/* ── 4 · El motor no rehace el asiento por la fecha estimada de pago ──────── */

/*
 * Es la misma función de 20260814_03 con una sola línea nueva al principio. El
 * candado deja pasar ese cambio en un mes cerrado (ver
 * `comprobante_solo_gestion`); si el motor igual rehiciera el asiento, el
 * candado de `asientos` lo frenaría adentro del bloque que atrapa errores y la
 * factura aparecería como «sin asentar» teniendo su asiento intacto.
 */
create or replace function tg_asiento_comprobante() returns trigger
language plpgsql as $$
declare
  v_error text;
begin
  if tg_op = 'UPDATE' and comprobante_solo_gestion(old, new) then
    return new;
  end if;

  if tg_op = 'DELETE' then
    perform asiento_borrar('comprobante', old.id);
    perform asiento_falla('comprobante', old.id, null);
    return old;
  end if;

  -- Un borrador todavía no es un hecho contable y un anulado dejó de serlo. El
  -- borrado explícito hace que pasar de confirmado a borrador se lleve el
  -- asiento en vez de dejarlo colgado en el mayor.
  if new.estado is distinct from 'confirmado' then
    perform asiento_borrar('comprobante', new.id);
    perform asiento_falla('comprobante', new.id, null);
    return new;
  end if;

  begin
    perform asiento_de_comprobante(new.id);
    v_error := null;
  exception when others then
    v_error := sqlerrm;
    raise warning 'Comprobante % guardado sin asiento: %', new.id, sqlerrm;
  end;

  perform asiento_falla('comprobante', new.id, v_error);
  return new;
end $$;
